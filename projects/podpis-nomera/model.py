#!/usr/bin/env python3
"""Порог платы для абонента. Не прогноз выручки: числа абонентов нет."""
import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parent
monthly = subprocess.check_output(
    ["python3", str(root / "sources" / "calc_month_fee.py")], text=True
).strip()

summary = (
    f"На странице услуги плата 3 ₽ в день [C3]: за 30 дней это {monthly} ₽, "
    "если тариф не делает услугу бесплатной. Доля таких тарифов не опубликована. "
    "Плата не останавливается, когда номер уже записали в книгу и подпись скрылась [C5]. "
    "Один лишний ответ в первые дни сам по себе этот месяц не окупает. "
    "Открытых данных, у скольких абонентов подпись вообще появляется, нет [C35, C38]."
)
flip = (
    "Выбор пересматривается 15 февраля 2027 или раньше, если появится замер доли ответов "
    "у сменивших номер против таких же без подписи [C38], или страница перестанет ограничивать "
    "показ номерами МегаФона [C6, C9]. Обещание защиты от мошенников из механизма не следует [K13]."
)
(root / "model_result.json").write_text(
    json.dumps({"summary": summary, "flip": flip}, ensure_ascii=False, indent=2) + "\n",
    encoding="utf-8",
)
(root / "output" / "econ.md").write_text(
    "\n".join([
        "# Порог платы",
        "",
        "Это не прогноз выручки: числа абонентов в открытых данных нет.",
        "",
        "| | |",
        "|---|---|",
        "| Плата в день | 3 ₽ [C3] |",
        f"| За 30 дней | {monthly} ₽, если тариф не бесплатный [C33] |",
        "| Что должно случиться, чтобы абоненту имело смысл | хотя бы один дополнительный ответ в месяц дороже этой платы [C34] |",
        "",
        flip,
        "",
    ]) + "\n",
    encoding="utf-8",
)
print(summary)
