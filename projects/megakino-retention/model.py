"""Экономика МегаКино: пороги безубыточности вариантов.

Запуск из корня репозитория:  python3 projects/megakino-retention/model.py
Результат: output/econ.md (таблицы) и model_result.json (короткий итог для паспорта).

Внутренних данных МегаФона нет (C86), поэтому модель не предсказывает прибыль, а отвечает на вопрос
«насколько должен измениться отток, чтобы вариант окупился». Все неизвестные заданы диапазонами
(тип ДОПУЩЕНИЕ); подставьте реальные значения из выгрузки — и пороги пересчитаются.
"""
import json
from itertools import product
from pathlib import Path

HERE = Path(__file__).resolve().parent

# ---- Открытые факты (id в реестре) ----
PRICE = 399            # ₽ за 30 дней [C16]
FREE_SWITCHES = 3      # бесплатных переключений в 30 дней [C18]
SWITCH_FEE = 30        # ₽ за 4-е и следующие [C18]
TARIFF_ARPU = {"Оптимальный": 950, "ВИП +": 1600}  # ₽ за 30 дней, витрина Москвы 09.11.2026 [C88]
OIBDA_MARGIN = 0.425   # рентабельность OIBDA МегаФона, 1-е полугодие 2026 [C105]
ALT_PRICES = {"START": 499, "Wink": 399, "PREMIER": 399, "Кинопоиск (Яндекс Плюс)": 449}  # [C104]

# ---- Допущения: диапазоны, а не оценки ----
PARTNER_SHARE = [0.5, 0.65, 0.8]     # доля цены, которая уходит кинотеатрам
SUB_CHURN = [0.10, 0.20, 0.30]       # месячный отток подписки МегаКино
HEAVY_SHARE = [0.05, 0.15, 0.30]     # доля подписчиков с 4+ переключениями в месяц; 5% — нижняя граница диапазона, не действующий порог
EXTRA_SWITCHES = [1, 2, 4]           # сколько платных переключений в месяц у них в среднем
MOBILE_CHURN = [0.01, 0.02, 0.03]    # месячный отток абонентов связи на тарифах пилота
ACTIVATION = [0.2, 0.4, 0.6]         # доля абонентов тарифа, кто активирует кино, если оно включено
# Центральные допущения порога, зафиксированного до запуска.
CENTRAL_P = 0.65
CENTRAL_MOBILE_CHURN = 0.02
CENTRAL_ACTIVATION = 0.40
# «ВИП +» — семья из трёх [C88]. Решение: кино одно на договор, не на каждый номер.
# Если платить придётся за каждый номер, пилот уходит на «Оптимальный» (там номер и договор совпадают).
NUMBERS_ON_VIP = 3


def o3_threshold(p, c, s, e):
    """Без платы за переключения: до какого оттока подписки нужно дойти, чтобы доход с подписчика
    за срок жизни не упал. Доход за срок жизни ≈ маржа в месяц / отток."""
    m_with_fee = PRICE * (1 - p) + s * e * SWITCH_FEE
    m_no_fee = PRICE * (1 - p)
    c_needed = c * m_no_fee / m_with_fee
    return {"fee_per_sub": s * e * SWITCH_FEE, "c_needed": c_needed, "rel_drop": 1 - c_needed / c}


def o4_threshold(arpu, p, m, a, numbers=1):
    """Кино в тарифе: на сколько процентных пунктов в месяц должен снизиться отток абонентов связи,
    чтобы окупить оплату кинотеатрам за активировавших. Ценность удержанного абонента ≈
    ARPU × маржа / отток (вклад за оставшийся срок жизни).
    numbers=1 — одно кино на договор. numbers>1 — кино на каждый номер договора (семья «ВИП +»)."""
    cost = a * PRICE * p * numbers       # ₽ в месяц на один договор тарифа
    value_per_saved = arpu * OIBDA_MARGIN / m
    dm = cost / value_per_saved          # нужное снижение оттока, доля в месяц
    return {"cost": cost, "dm_pp": dm * 100, "rel_drop": dm / m}


def o2_close(p):
    """Закрыть: теряем валовую маржу подписки; выигрыш — только постоянные затраты, которых в
    открытых данных нет. Плюс риск потери удержания абонентов, если оно есть (X47)."""
    return PRICE * (1 - p)


def two_active_margin(p):
    """Два кинотеатра одновременно, если кинотеатрам платят за каждый активный каталог:
    доля p берётся дважды. Маржа ≤ 0 означает, что удержание не окупает вариант ни при каком оттоке."""
    return PRICE * (1 - 2 * p)


def rng(vals):
    return f"{min(vals):.1f}–{max(vals):.1f}" if min(vals) != max(vals) else f"{vals[0]:.1f}"


def main():
    lines = ["# Экономика МегаКино: пороги безубыточности", "",
             "_Собрано скриптом `projects/megakino-retention/model.py`. Не редактируйте вручную._", "",
             "Внутренних данных нет [C86], поэтому считаем не прибыль, а **пороги**: какое изменение "
             "оттока нужно, чтобы вариант окупился. Факты — из реестра, неизвестные — диапазонами "
             "(`ДОПУЩЕНИЕ`). Подставьте выгрузку команды МегаФона в начало скрипта — пороги пересчитаются.", ""]

    # 0. ценность для зрителя
    total = sum(ALT_PRICES.values())
    lines += ["## 0. Что получает зритель", "",
              f"`ФАКТ` Отдельные подписки на 4 из 5 кинотеатров вместе — {total} ₽ в месяц [C104], "
              f"МегаКино — {PRICE} ₽ [C16]. Зрителю одного сервиса МегаКино дешевле START "
              f"({ALT_PRICES['START']} ₽) и Кинопоиска ({ALT_PRICES['Кинопоиск (Яндекс Плюс)']} ₽) "
              f"на {ALT_PRICES['Кинопоиск (Яндекс Плюс)'] - PRICE}–{ALT_PRICES['START'] - PRICE} ₽, "
              f"равно Wink и PREMIER ({ALT_PRICES['Wink']} ₽) и дороже МТС Premium с KION (349 ₽) "
              f"[C138, C137]. Большая экономия против суммы четырёх подписок есть только у тех, "
              f"кто переключается [C139].", ""]

    # 1. как есть / закрыть
    lines += ["## 1. Как есть и закрыть", "",
              "| Доля кинотеатров в цене (`ДОПУЩЕНИЕ`) | Валовая маржа с подписчика, ₽/мес |", "|---|---|"]
    for p in PARTNER_SHARE:
        lines.append(f"| {p:.0%} | {o2_close(p):.0f} |")
    lines += ["", "Закрытие экономит только постоянные затраты (команда, поддержка, маркетинг) — их в открытых "
              "данных нет. Значит, закрывать имеет смысл, только если они больше валовой маржи всей базы, "
              "**и** выгрузка не показала вклада в удержание абонентов связи [X47].", ""]

    # 2. O3
    lines += ["## 2. Убрать плату за переключения", "",
              "Сколько приносит плата за переключения и насколько должен упасть отток подписки, "
              "чтобы её отмена окупилась (доля кинотеатров 65%, `ДОПУЩЕНИЕ`).", "",
              "| Переключаются 4+ раз | Платных переключений у них | Плата, ₽ на подписчика в мес | "
              "Нужно снизить отток подписки, относительно |", "|---|---|---|---|"]
    o3_all = []
    for s, e in product(HEAVY_SHARE, EXTRA_SWITCHES):
        r = o3_threshold(0.65, 0.2, s, e)
        lines.append(f"| {s:.0%} | {e} | {r['fee_per_sub']:.1f} | {r['rel_drop']:.1%} |")
    for p, c, s, e in product(PARTNER_SHARE, SUB_CHURN, HEAVY_SHARE, EXTRA_SWITCHES):
        o3_all.append(o3_threshold(p, c, s, e)["rel_drop"])
    lines += ["", f"По всем сочетаниям допущений нужно снижение оттока подписки на "
              f"{min(o3_all):.1%}–{max(o3_all):.1%} (относительно). От текущего уровня оттока порог не зависит: "
              "это доля платы за переключения в марже подписчика.", "",
              "**Вывод.** Плата за переключения приносит мало денег на подписчика, но бьёт по тем, ради "
              "кого продукт существует [K6]. Отмена окупается уже при небольшом росте удержания. Если "
              "кинотеатры получают деньги за каждое переключение, порог выше — условия партнёров неизвестны.", ""]

    # 3. O4
    lines += ["## 3. Кино в тарифе", "",
              "Оплата кинотеатрам за активировавших против удержания абонентов связи. Вклад удержанного "
              f"абонента — ARPU тарифа × рентабельность OIBDA {OIBDA_MARGIN:.1%} [C105] за оставшийся срок жизни. "
              "Доля кинотеатров 65%.", "",
              "При оттоке 2% в месяц (`ДОПУЩЕНИЕ`):", "", "| Тариф | Отток абонентов в мес | Активируют кино | Затраты, ₽ на абонента в мес | "
              "Нужно снизить отток, п.п. в мес | Относительно |", "|---|---|---|---|---|---|"]
    o4_all = []
    for t, arpu in TARIFF_ARPU.items():
        for m, a in product(MOBILE_CHURN, ACTIVATION):
            r = o4_threshold(arpu, 0.65, m, a)
            if m == 0.02:
                lines.append(f"| {t} {arpu} ₽ [C88] | {m:.0%} | {a:.0%} | {r['cost']:.0f} | {r['dm_pp']:.2f} | {r['rel_drop']:.0%} |")
        for p, m, a in product(PARTNER_SHARE, MOBILE_CHURN, ACTIVATION):
            o4_all.append((t, o4_threshold(arpu, p, m, a)["rel_drop"]))
    opt = [x for t, x in o4_all if t == "Оптимальный"]
    vip = [x for t, x in o4_all if t == "ВИП +"]
    lines += ["", f"По всем сочетаниям допущений: «Оптимальный» — нужно снизить отток абонентов на "
              f"{min(opt):.0%}–{max(opt):.0%} (относительно), «ВИП +» — на {min(vip):.0%}–{max(vip):.0%}.", "",
              "**Вывод.** На дорогом тарифе кино окупается при заметно меньшем эффекте, чем на среднем. "
              "Главный рычаг затрат — доля активирующих: если кино включено, но им не пользуются, оно почти "
              "ничего не стоит (при оплате за активацию), но и не удерживает. Таблица — одно кино на договор. "
              "Если кино на каждый номер семьи «ВИП +», затраты и порог втрое выше: см. раздел 5.", ""]

    # 4. два активных кинотеатра — проверка упущенного хода, не новый тариф
    lines += ["## 4. Два кинотеатра одновременно", "",
              "Люди при запуске спорили с правилом «один кинотеатр в момент» [C22, C102]. "
              "Если за каждый активный каталог платят ту же долю цены, маржа подписки:", "",
              "| Доля кинотеатров (`ДОПУЩЕНИЕ`) | Маржа при двух активных, ₽/мес |", "|---|---|"]
    two_margins = []
    for p in PARTNER_SHARE:
        m2 = two_active_margin(p)
        two_margins.append(m2)
        lines.append(f"| {p:.0%} | {m2:.0f} |")
    lines += ["",
              "При доле 50% маржа ноль, при 65% и 80% она отрицательная. "
              "Снижение оттока такую маржу не вытягивает: удерживать нечего. "
              "Вариант жив только если договор «за абонента», а не за каждый активный каталог. "
              "Такого условия в открытых данных нет, поэтому отдельным вариантом его не выносим.", ""]

    # 5. порог пилота до запуска — центральная точка, не минимум диапазона
    lines += ["## 5. Порог пилота до запуска", "",
              "Диапазон из раздела 3 нельзя подставить после результата: нижний край — самый лёгкий случай. "
              "Зафиксировано **до запуска**: доля кинотеатров "
              f"{CENTRAL_P:.0%}, активация {CENTRAL_ACTIVATION:.0%}, базовый отток "
              f"{CENTRAL_MOBILE_CHURN:.0%} в месяц, платим за активацию, маржа — OIBDA {OIBDA_MARGIN:.1%} [C105]. "
              "Цена «ВИП +» 1600 ₽ — цена договора на семью из трёх, не цена одного номера [C88].",
              ""]
    central = {}
    per_number = o4_threshold(TARIFF_ARPU["ВИП +"], CENTRAL_P, CENTRAL_MOBILE_CHURN,
                              CENTRAL_ACTIVATION, numbers=NUMBERS_ON_VIP)
    lines.append("| Тариф | Единица оплаты | Затраты, ₽ на договор в мес | Порог: снизить отток, п.п. в месяц | Относительно базовых 2% |")
    lines.append("|---|---|---|---|---|")
    for t, arpu in TARIFF_ARPU.items():
        r = o4_threshold(arpu, CENTRAL_P, CENTRAL_MOBILE_CHURN, CENTRAL_ACTIVATION)
        central[t] = r
        unit = "одно кино на договор" if t == "ВИП +" else "номер и договор совпадают"
        lines.append(f"| {t} {arpu} ₽ [C88] | {unit} | {r['cost']:.0f} | {r['dm_pp']:.2f} | {r['rel_drop']:.0%} |")
    lines.append(f"| ВИП + {TARIFF_ARPU['ВИП +']} ₽ [C88] | кино на каждый из {NUMBERS_ON_VIP} номеров | "
                 f"{per_number['cost']:.0f} | {per_number['dm_pp']:.2f} | {per_number['rel_drop']:.0%} |")
    lines += ["",
              f"Решение: пилот на «ВИП +», порог **{central['ВИП +']['dm_pp']:.2f} п.п. в месяц**, "
              "если кино одно на договор, не на каждый номер. "
              "Успех — отток абонентов связи у всех, **кому предложили**, ниже контроля не меньше чем на эту величину. "
              "Считать только согласившихся нельзя: согласие само отбирает тех, кто и так остаётся. "
              f"Если кино нельзя оформить одно на договор и платить придётся за каждый номер, "
              f"порог «ВИП +» становится {per_number['dm_pp']:.2f} п.п. — этот вариант не берём. "
              f"Тогда пилот на «Оптимальном» и порог **{central['Оптимальный']['dm_pp']:.2f} п.п.** "
              "Если платят за всех абонентов тарифа, а не за активацию, порог пересчитывают этим скриптом "
              "до чтения итога.", ""]

    lines += ["## Чего мы не знаем", "",
              "- Условия партнёров: доля цены, оплата за подписчика или за переключение. От этого зависят оба порога.",
              "- Отток подписки, отток абонентов связи и распределение переключений. Порог пилота утверждён: «ВИП +», 0,31 п.п., одно кино на договор; если кино на каждый номер — «Оптимальный» и 0,51 п.п.",
              "- Постоянные затраты на продукт — без них нельзя сравнить «как есть» и «закрыть» в рублях.",
              "- Рентабельность OIBDA — по компании в целом; маржа связи на конкретном тарифе может отличаться.", ""]
    out = HERE / "output" / "econ.md"
    out.write_text("\n".join(lines), encoding="utf-8")

    opt_c, vip_c = central["Оптимальный"], central["ВИП +"]
    summary = (f"Пороги безубыточности (`output/econ.md`, скрипт `model.py`). Отмена платы за переключения окупается, "
               f"если отток подписки снизится на {min(o3_all):.1%}–{max(o3_all):.1%}: плата приносит мало денег. "
               f"Кино в тарифе окупается, если отток абонентов связи снизится на {min(opt):.0%}–{max(opt):.0%} "
               f"на «Оптимальном» и на {min(vip):.0%}–{max(vip):.0%} на «ВИП +» (одно кино на договор). "
               f"Пилот зафиксирован на «ВИП +»: не меньше {vip_c['dm_pp']:.2f} п.п. в месяц, "
               f"если кино одно на договор. Если кино на каждый из {NUMBERS_ON_VIP} номеров, порог "
               f"{per_number['dm_pp']:.2f} п.п. — тогда пилот на «Оптимальном» и не меньше {opt_c['dm_pp']:.2f} п.п. "
               f"Два активных кинотеатра при оплате за каталог дают маржу {min(two_margins):.0f}…{max(two_margins):.0f} ₽ "
               f"и отдельным вариантом не вынесены.")
    flip = ("если отток абонентов связи у тех, кому предложили, снизится меньше 0,31 п.п. в месяц на «ВИП +» "
            "(одно кино на договор), пилот сворачивают. Если кино нельзя оформить одно на договор и платить "
            "придётся за каждый номер, пилот переносят на «Оптимальный» с порогом 0,51 п.п. "
            "Если платят за всех абонентов тарифа, а не за активацию, порог пересчитать до чтения итога. "
            "Если кинотеатры берут деньги за каждое переключение, пересчитать и отмену платы за переключения. "
            "Два одновременных кинотеатра при оплате за каталог не окупаются ни при каком оттоке.")
    (HERE / "model_result.json").write_text(json.dumps({"summary": summary, "flip": flip}, ensure_ascii=False, indent=1),
                                            encoding="utf-8")
    print(f"Записано: {out}")
    print(summary)


if __name__ == "__main__":
    main()
