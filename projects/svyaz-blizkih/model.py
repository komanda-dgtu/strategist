"""Прогноз сигнала O3 при выбранной проверке O5.

Запуск из корня репозитория:
  python3 projects/svyaz-blizkih/model.py

Учебные входы — бриф. Темп 100 подходящих групп в неделю — пример записи брифа
про набор (600 групп за 6 недель), не измеренный поток оператора.
Польза клиенту (ограничение интернета) и активность (просмотр остатка или
выделение) считаются разными показателями.
"""
import json
import sys
from pathlib import Path

import money_boundary

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
import pilot  # noqa: E402

HERE = Path(__file__).resolve().parent

CONNECTED = 8000
BAU_ACTIVE = 5000
INACTIVE = CONNECTED - BAU_ACTIVE  # 3000, потолок добавки за один месяц
BAU_RATE = BAU_ACTIVE / CONNECTED  # 0.625, доля по всем подключённым, не по подходящим

# Допущение темпа, пока I квартал не назовёт свой поток.
WEEKLY = 100
DEC_WEEKS = 4
HOLDOUT = 0.5
INTAKE_WEEKS = 6

# Наименьшее улучшение доли ограничений из учебного примера записи, не наша база.
BENEFIT_BASE = 0.12
BENEFIT_TARGET = 0.09


def main():
    events = WEEKLY * DEC_WEEKS
    signal_arm = int(events * (1 - HOLDOUT))
    # Верх иллюстрации: каждая группа сигнала была неактивной и совершила действие.
    a_hi = signal_arm
    active_hi = BAU_ACTIVE + a_hi

    lift_rows = []
    for target in (0.70, 0.75, 0.80):
        row = pilot.sample_size(BAU_RATE, target)
        row["weeks_at_pace"] = row["total"] / WEEKLY
        row["fits_intake"] = row["weeks_at_pace"] <= INTAKE_WEEKS
        lift_rows.append(row)
    # Порог, который укладывается в 6 недель при этом темпе: 62,5 % → 75 %.
    detectable = next(r for r in lift_rows if r["target"] == 0.75)
    a_if_that_lift = int(round(signal_arm * (detectable["target"] - BAU_RATE)))
    active_if_that_lift = BAU_ACTIVE + a_if_that_lift

    benefit = pilot.sample_size(BENEFIT_BASE, BENEFIT_TARGET)
    benefit["weeks_at_pace"] = benefit["total"] / WEEKLY

    intake = WEEKLY * INTAKE_WEEKS
    lines = []
    lines.append("# Расчёт: активность сигнала и окупаемость")
    lines.append("")
    lines.append("Учебные числа брифа. Темп 100 групп в неделю — пример записи, не поток оператора.")
    lines.append("")
    lines.append("## Активность последнего месяца, основной сценарий")
    lines.append("")
    lines.append(f"Подключённых: {CONNECTED}. Без изменений активных: {BAU_ACTIVE}.")
    lines.append(f"Неактивный запас, больше которого один месяц не прибавляет: {INACTIVE}.")
    lines.append(f"Допущение темпа: {WEEKLY} подходящих групп в неделю, последний месяц = {DEC_WEEKS} недели, событий = {events}.")
    lines.append(f"Половина семей остаётся в сравнении, в сигнал попадает {signal_arm}.")
    lines.append(f"A — группы, которые посмотрели остаток или успешно выделили интернет только из-за сигнала.")
    lines.append(f"При этом темпе 0 ≤ A ≤ {a_hi}, активные от {BAU_ACTIVE} до {active_hi}.")
    lines.append(f"Если эффект равен +12,5 п.п. (порог, который видят 6 недель набора), A = {a_if_that_lift}, активные = {active_if_that_lift}.")
    lines.append(f"Потолок определения при {CONNECTED} подключённых: {CONNECTED}. Он достижим, только если все {INACTIVE} неактивных групп совершат действие. Сигнал приходит лишь при низкой доле, поэтому этот потолок не план.")
    lines.append("Неблагоприятный сценарий, пилота нет: A = 0, активные = 5000.")
    lines.append("")
    lines.append("## Размер пилота")
    lines.append("")
    lines.append("База 62,5 % — доля активных среди всех подключённых, не доля среди семей с низкой долей. До первого сообщения её заменяют подсчётом I квартала.")
    lines.append("")
    lines.append("| было | цель | всего групп | недель при 100 в неделю | укладывается в 6 недель |")
    lines.append("|---|---|---|---|---|")
    for r in lift_rows:
        fits = "да" if r["fits_intake"] else "нет"
        lines.append(f"| {r['base']:.1%} | {r['target']:.1%} | {r['total']} | {r['weeks_at_pace']:.1f} | {fits} |")
    lines.append("")
    lines.append(f"Набор 6 недель при 100 в неделю даёт {intake} семей, из них половина с сигналом.")
    lines.append(f"В эти 6 недель помещается сравнение {detectable['total']} семей на шаг {BAU_RATE:.1%} → {detectable['target']:.1%}.")
    lines.append(f"Шаг до 70 % требует {lift_rows[0]['total']} семей и {lift_rows[0]['weeks_at_pace']:.1f} недель. В 6 недель он не помещается.")
    lines.append("")
    lines.append("## Польза клиенту, отдельно")
    lines.append("")
    lines.append(f"Учебный пример порога {BENEFIT_BASE:.0%} → {BENEFIT_TARGET:.0%}: {benefit['total']} семей, {benefit['weeks_at_pace']:.1f} недель при 100 в неделю.")
    lines.append("Это не наша измеренная база. Открытие ссылки в эту долю не входит.")
    lines.append("Шесть недель — пример длины набора, не длина II квартала. При том же темпе набор на 32,8 недели дотягивается, только если случайное распределение продолжается в III–IV кварталах.")
    lines.append("")
    lines.append("## Прибыль и окупаемость")
    lines.append("")
    lines.append("Дополнительная валовая прибыль по кварталам: 0, 0, 0, 0 руб.")
    lines.append("Предельная сумма вложений, которую вернёт плановый год при этих нулях: 0 руб.")
    signal_families = int(intake * (1 - HOLDOUT))
    lines.append("Цена человеко-месяца Ц в брифе не задана. Её называет финансовая команда.")
    lines.append("Оплаченных месяцев, чтобы вернуть 3 человеко-месяца: 3 × Ц / 500.")
    lines.append(f"Семей в сигнале пилота при примере темпа: {signal_families} (6 недель × 100 в неделю × половина).")
    lines.append(f"На одну такую семью: (3 × Ц / 500) / {signal_families} = Ц / {500 * signal_families // 3}.")
    lines.append("Рост активности A в формулу не подставляется. Если сигнал продолжится после пилота, то же число месяцев делится на все семьи сигнала за год.")
    text = "\n".join(lines) + "\n"
    (HERE / "sources" / "activity_forecast.md").write_text(text, encoding="utf-8")

    econ = []
    econ.append("# Экономика выбранной проверки")
    econ.append("")
    econ.append("Выбран O5. В I квартале рассылки нет. Основной сценарий дальше — пилот сигнала во II квартале и продолжение того же сигнала в III–IV. Неблагоприятный — пилота нет.")
    econ.append("")
    econ.append("Польза и активность расходятся. Польза — ограничили ли интернет из-за объёма. Активность — посмотрели ли остаток общего пакета или успешно выделили интернет. Второе попадает в перепись последнего месяца напрямую. Первое в перепись не переводится.")
    econ.append("")
    econ.append(f"При допущении {WEEKLY} подходящих групп в неделю и половине семей в сравнении последний месяц даёт {signal_arm} групп с сигналом. Активные: от {BAU_ACTIVE} до {active_hi}. Если сработает только наименьший шаг, который видно за 6 недель (+12,5 п.п.), активных {active_if_that_lift}. Потолок определения {CONNECTED} в этот темп не входит.")
    econ.append("")
    econ.append(f"Пилот активности: {detectable['total']} семей на шаг {BAU_RATE:.1%} → {detectable['target']:.1%}, около {detectable['weeks_at_pace']:.1f} недель при {WEEKLY} в неделю. Набор 6 недель при этом темпе даёт {intake}. Шаг до 70 % за 6 недель не набирается ({lift_rows[0]['total']} семей).")
    econ.append("")
    econ.append(f"Польза по учебному примеру {BENEFIT_BASE:.0%} → {BENEFIT_TARGET:.0%}: {benefit['total']} семей и {benefit['weeks_at_pace']:.1f} недель. Это пример записи, не база оператора. II квартал его не закрывает.")
    econ.append("")
    econ.append("Разрыв до 285 млн руб. от 279 млн — 6 млн руб., 12 000 месяцев по 500 руб. Дополнительная прибыль по кварталам 0, 0, 0, 0. Пока оплаченных месяцев нет, год не покрывает положительную цену разработки.")
    econ.append("")
    econ.append("Формула при неизвестной цене человеко-месяца Ц: чтобы вернуть 3 человеко-месяца, нужно 3 × Ц / 500 дополнительных оплаченных месяцев. На одну семью сигнала в пилоте при N = 300 это Ц / 50 000 месяцев. Ц предстоит узнать у финансовой команды. N = 300 — пример: 6 недель × 100 групп в неделю × половина, не измеренный поток.")
    econ.append("")
    econ.append("Потолок, не вклад сигнала: 6 500 групп × 500 руб. × 1 месяц = 3,25 млн руб. Три месяца у всех групп — 9,75 млн только как арифметика.")
    econ.append("")
    econ.append("Граница удержания в прибыль не подставлена. Пилот 300 семей при 4 номерах и 9 месяцах даёт не больше 5,4 млн и 6 млн не закрывает. Пример сигнала на весь год закрывает 6 млн только при двух номерах и доле 2/3 до декабря. Один лишний месяц при тех же двух номерах — 1,8 млн даже если останутся все. Подробности — sources/money_boundary.md.")
    econ.append("")
    econ.append("Доход группы за второй и третий год — условный диапазон: при k номерах от 0 до k × 6 000 руб. за полный год. Вероятность продолжения неизвестна. В разрыв планового года этот диапазон не входит.")
    econ.append("")
    econ.append("Если в марте P не меньше V, одна предотвращённая остановка даёт m месяцев и 500 × m руб. Для 6 млн нужно 12 000 таких месяцев. При одном месяце на остановку это 12 000 номеров за год. С удержанием сигнала эти месяцы не складываются.")
    (HERE / "output" / "econ.md").write_text("\n".join(econ) + "\n", encoding="utf-8")
    money_boundary.build()

    summary = (
        f"Закладываемая прибыль в основном, неблагоприятном и благоприятном ходе — 279 млн руб. "
        f"Активные последнего месяца в основном ходе — от {BAU_ACTIVE} до {active_hi} "
        f"при темпе-допущении {WEEKLY} групп в неделю; в благоприятном, если все семьи сигнала декабря делают действие, — {active_hi}. "
        f"Граница удержания в эту прибыль не входит. Пилот на 300 семьях не закрывает 6 млн даже при 4 номерах и 9 месяцах: ёмкость 5,4 млн. "
        f"Пример сигнала на весь год закрывает 6 млн только при двух номерах и двух третях семей до декабря. "
        f"Один лишний месяц вместо конца года при двух номерах даёт 1,8 млн. "
        f"Одна предотвращённая остановка — m месяцев и 500 × m руб.; для 6 млн нужно 12 000 таких месяцев. "
        f"Второй и третий год одной группы из k номеров — от 0 до k × 6 000 руб. и в разрыв этого года не входят. "
        f"Три человеко-месяца возвращаются при 3 × Ц / 500 оплаченных месяцев; на семью пилота при N = 300 это Ц / 50 000."
    )
    flip = (
        "Пилот не начинается, если записка не разрешает сигнал. "
        "Расширение в III квартале не начинается, если за 6 недель доля просмотра или выделения "
        "не доходит с 62,5 % до 75 % на базе, которую в марте заменят доли подходящих семей. "
        "Рост активности при нуле оплаченных месяцев деньги года не открывает. "
        "Если в марте P не меньше V, первый путь — неоплата, но 6 млн всё равно требуют 12 000 оплаченных месяцев, а не самого неравенства."
    )
    (HERE / "model_result.json").write_text(
        json.dumps({"summary": summary, "flip": flip}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(text)
    print("Записано sources/activity_forecast.md, sources/money_boundary.md, output/econ.md, model_result.json")


if __name__ == "__main__":
    main()
