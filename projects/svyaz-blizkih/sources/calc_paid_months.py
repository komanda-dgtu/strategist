"""Потолок вклада в валовую прибыль: номера × 500 руб. × месяцы внутри года.

Не прогноз спроса. 6 500 — оценка подключённых семейных групп на конец базового года.
Одна группа в этой арифметике условно равна одному номеру. Цель разрыва — 12 000 месяцев.
"""
RATE = 500
NEED = 12_000
for groups, months in ((6_500, 1), (6_500, 3)):
    months_total = groups * months
    print(f"групп={groups} месяцы={months} месяцев={months_total} "
          f"руб={months_total * RATE} до_12000={NEED - months_total}")
