PILOT_MAY = 100

# Продолжение примера, апрель–декабрь: 4 недели × 100 × половина = 200 семей в месяц.
PER_MONTH = 200
MONTHS_LEFT = (9, 8, 7, 6, 5, 4, 3, 2, 1)  # апрель … декабрь, включая месяц сигнала


def rub(months):
    return months * RATE


def share(need, capacity):
    if capacity <= 0:
        return None
    return need / capacity


def pct(value):
    if value is None or value > 1:
        return "нельзя"
    return f"{value * 100:.1f} %".replace(".", ",")


def capacity_flat(n, k, m):
    return n * k * m


def year_capacity(k, stay_to_december):
    """Число дополнительных месяцев номеров при доле 100 %."""
    if stay_to_december:
        return PER_MONTH * sum(m * k for m in MONTHS_LEFT)
    return PER_MONTH * len(MONTHS_LEFT) * k * 1


def pilot_timed(k):
    return PILOT_APRIL * k * 9 + PILOT_MAY * k * 8


def row(label, cap):
    cells = [label, f"{cap}", f"{rub(cap)}"]
    for _, need in TARGETS:
        cells.append(pct(share(need, cap)))
    return cells


